package rosa.archive.core.serialize;

import org.junit.jupiter.api.Test;
import rosa.archive.model.BookImage;
import rosa.archive.model.ImageList;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The image list writer must produce exactly what {@link ArchiveReaders#readImageList} reads.
 */
class ArchiveWritersTest {

    @Test
    void imageListRoundTripsTheRealFormat() throws IOException {
        // Rows as they occur in the archive: missing marker, no dimensions, label, auto label
        String csv = "*Douce195.binding.frontcover.tif\n"
                + "Douce195.frontmatter.pastedown.tif,3000,4000\n"
                + "Douce195.001r.tif,3000,4000,[title page]\n"
                + "Douce195.001v.tif,3000,4000,##1v\n"
                + "*Douce195.002r.tif,3000,4000\n";
        Path file = Files.createTempFile("images", ".csv");
        Files.writeString(file, csv, StandardCharsets.UTF_8);

        List<String> errors = new ArrayList<>();
        ImageList images = ArchiveReaders.readImageList(file, errors);
        assertTrue(errors.isEmpty(), errors.toString());

        assertEquals(csv, ArchiveWriters.imageListCsv(images.getImages()));
        Files.delete(file);
    }

    @Test
    void imageListRoundTripsTheFixtureBook() throws Exception {
        Path fixture = Path.of(getClass().getClassLoader().getResource("archive").toURI())
                .resolve("rose").resolve("Douce195").resolve("Douce195.images.csv");
        List<String> errors = new ArrayList<>();
        ImageList images = ArchiveReaders.readImageList(fixture, errors);
        assertTrue(errors.isEmpty(), errors.toString());

        String written = ArchiveWriters.imageListCsv(images.getImages());
        ImageList reread = ArchiveReaders.readImageList(writeTemp(written), errors);
        assertTrue(errors.isEmpty(), errors.toString());

        assertEquals(images.getImages().size(), reread.getImages().size());
        for (int i = 0; i < images.getImages().size(); i++) {
            BookImage a = images.getImages().get(i);
            BookImage b = reread.getImages().get(i);
            assertEquals(a.getId(), b.getId());
            assertEquals(a.isMissing(), b.isMissing());
            assertEquals(a.getWidth(), b.getWidth());
            assertEquals(a.getHeight(), b.getHeight());
            assertEquals(a.getName(), b.getName());
            assertEquals(a.isAutoGeneratedName(), b.isAutoGeneratedName());
        }
    }

    private static Path writeTemp(String content) throws IOException {
        Path file = Files.createTempFile("images", ".csv");
        file.toFile().deleteOnExit();
        Files.writeString(file, content, StandardCharsets.UTF_8);
        return file;
    }
}
