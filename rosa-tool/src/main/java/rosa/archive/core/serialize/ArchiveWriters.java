package rosa.archive.core.serialize;

import rosa.archive.core.ArchiveNameParser;
import rosa.archive.model.BookImage;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Writers for archive files whose format {@link ArchiveReaders} reads, so that every
 * command producing them writes the same layout the rest of the tool expects.
 */
public final class ArchiveWriters {

    private static final ArchiveNameParser PARSER = new ArchiveNameParser();

    private ArchiveWriters() {
    }

    /**
     * Renders an image list in the archive format read by {@link ArchiveReaders#readImageList}:
     * one row per image, {@code [*]id,width,height[,label]} with no header. A leading
     * {@code *} marks a missing image, the dimensions are left out when both are unknown and
     * there is no label, and a label is written only when the image has a name other than
     * the one derived from its id; an auto-generated name is prefixed with {@code ##}.
     *
     * @param images the images in page order
     * @return the CSV text, ending with a newline unless empty
     */
    public static String imageListCsv(List<BookImage> images) {
        StringBuilder sb = new StringBuilder();
        for (BookImage image : images) {
            String id = image.getId();
            if (image.isMissing()) {
                sb.append(ArchiveNameParser.MISSING_PREFIX);
            }
            sb.append(id);

            String name = image.getName();
            boolean hasLabel = name != null && !name.isEmpty()
                    && (image.isAutoGeneratedName() || !name.equals(PARSER.shortName(id)));
            boolean hasSize = image.getWidth() > 0 || image.getHeight() > 0;

            if (hasSize || hasLabel) {
                sb.append(',').append(image.getWidth()).append(',').append(image.getHeight());
            }
            if (hasLabel) {
                sb.append(',');
                if (image.isAutoGeneratedName()) {
                    sb.append(ArchiveNameParser.GENERATED_PREFIX);
                }
                sb.append(name);
            }
            sb.append('\n');
        }
        return sb.toString();
    }

    /**
     * Writes an image list file in the archive format.
     *
     * @param path   the {@code .images.csv} or {@code .images.crop.csv} file
     * @param images the images in page order
     * @throws IOException if writing fails
     */
    public static void writeImageList(Path path, List<BookImage> images) throws IOException {
        Files.writeString(path, imageListCsv(images), StandardCharsets.UTF_8);
    }
}
