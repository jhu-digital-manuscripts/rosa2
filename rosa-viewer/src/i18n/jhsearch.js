/**
 * Get translations for a specific language.
 * Falls back to English if the language is not available.
 *
 * @param {string} lang - Language code
 * @returns {Object} Translation object
 */
export function getTranslations(lang = 'en') {
  return jhsearchTranslations[lang] || jhsearchTranslations.en;
}

/**
 * Simple translation function with interpolation.
 *
 * @param {string} key - Translation key
 * @param {Object} translations - Translation object
 * @param {Object} params - Interpolation parameters
 * @returns {string} Translated string
 */
export function t(key, translations, params = {}) {
  let text = translations[key] || key;

  // Handle pluralization
  if (params.count !== undefined && params.count !== 1) {
    const pluralKey = `${key}_plural`;
    if (translations[pluralKey]) {
      text = translations[pluralKey];
    }
  }

  // Interpolate parameters
  Object.entries(params).forEach(([param, value]) => {
    text = text.replace(new RegExp(`\\{\\{${param}\\}\\}`, 'g'), value);
  });

  return text;
}

export default jhsearchTranslations;
